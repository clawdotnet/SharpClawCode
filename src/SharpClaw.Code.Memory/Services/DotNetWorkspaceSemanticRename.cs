using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Rename;
using SharpClaw.Code.Memory.Abstractions;
using SharpClaw.Code.Protocol.Models;

namespace SharpClaw.Code.Memory.Services;

public sealed partial class DotNetWorkspaceSemanticService
{
    /// <inheritdoc />
    public async Task<CSharpRenamePlan> PlanRenameAsync(DotNetWorkspaceRequest request, CSharpToolArguments arguments, IDotNetWorkspaceEvaluationAuthorization? authorization, CancellationToken cancellationToken)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(arguments.NewName);
        if (!SyntaxFacts.IsValidIdentifier(arguments.NewName) || SyntaxFacts.GetKeywordKind(arguments.NewName) != SyntaxKind.None) throw new ArgumentException("newName must be a valid non-keyword C# identifier.");
        using var lease = await cache.AcquireAsync(request, authorization, cancellationToken).ConfigureAwait(false);
        var (resolution, candidates) = await ResolveAsync(lease, arguments.Query(), cancellationToken).ConfigureAwait(false);
        if (resolution.Symbol is null) return new(resolution, arguments.NewName, [], ["Rename requires one exact source symbol."]);
        var original = lease.Snapshot!.Solution;
        var renamed = await Renamer.RenameSymbolAsync(original, candidates[0].Symbol, new SymbolRenameOptions(false, false, false, false), arguments.NewName, cancellationToken).ConfigureAwait(false);
        var changes = new Dictionary<string, CSharpRenameChange>(OperatingSystem.IsWindows() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal);
        foreach (var projectChange in renamed.GetChanges(original).GetProjectChanges())
        {
            foreach (var id in projectChange.GetChangedDocuments())
            {
                var previous = original.GetDocument(id)!;
                var updated = renamed.GetDocument(id)!;
                if (previous.FilePath is null) return new(resolution, arguments.NewName, [], ["A generated document has no writable physical path."]);
                var path = pathService.GetCanonicalFullPath(previous.FilePath);
                if (!DotNetWorkspaceTargetResolver.IsWithin(lease.Target.WorkspaceRoot, path)) return new(resolution, arguments.NewName, [], ["A changed document escapes the workspace boundary."]);
                var before = (await previous.GetTextAsync(cancellationToken).ConfigureAwait(false)).ToString();
                if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) || before.TrimStart().StartsWith("// <auto-generated", StringComparison.OrdinalIgnoreCase)) return new(resolution, arguments.NewName, [], ["Generated documents cannot be renamed: " + Relative(lease.Target.WorkspaceRoot, path)]);
                var syntax = await updated.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
                if (syntax?.GetAnnotatedNodesAndTokens(ConflictAnnotation.Kind).Any() == true) return new(resolution, arguments.NewName, [], ["Roslyn reported an unresolved rename conflict."]);
                var after = (await updated.GetTextAsync(cancellationToken).ConfigureAwait(false)).ToString();
                if (before == after) continue;
                var change = new CSharpRenameChange(Relative(lease.Target.WorkspaceRoot, path), before, after);
                if (changes.TryGetValue(path, out var linked) && linked.ContentAfter != after) return new(resolution, arguments.NewName, [], ["Linked document contexts disagree on the resulting text."]);
                changes[path] = change;
            }
        }
        foreach (var project in renamed.Projects)
        {
            var oldCompilation = await original.GetProject(project.Id)!.GetCompilationAsync(cancellationToken).ConfigureAwait(false);
            var newCompilation = await project.GetCompilationAsync(cancellationToken).ConfigureAwait(false);
            var existing = oldCompilation?.GetDiagnostics(cancellationToken).Where(item => item.Severity == DiagnosticSeverity.Error).Select(item => item.Id + ":" + item.GetMessage()).ToHashSet(StringComparer.Ordinal) ?? [];
            if (newCompilation?.GetDiagnostics(cancellationToken).Any(item => item.Severity == DiagnosticSeverity.Error && !existing.Contains(item.Id + ":" + item.GetMessage())) == true) return new(resolution, arguments.NewName, [], ["Rename would introduce compiler errors; no changes were applied."]);
        }
        return new(resolution, arguments.NewName, changes.Values.OrderBy(change => change.Path, StringComparer.Ordinal).ToArray(), []);
    }
}
